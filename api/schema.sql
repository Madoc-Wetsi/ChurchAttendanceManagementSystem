CREATE DATABASE IF NOT EXISTS church_attendance
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE church_attendance;

-- ------------------------------------------------------------
--  members — the church register
--  `id` is generated by the front end (js/store.js uid()) so a
--  record created while offline can be saved later without a
--  clash. Keep it as a string; do NOT make it AUTO_INCREMENT.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS members (
  id        VARCHAR(40)  NOT NULL,
  first     VARCHAR(120) NOT NULL DEFAULT '',
  last      VARCHAR(120) NOT NULL DEFAULT '',
  email     VARCHAR(190)          DEFAULT '',
  phone     VARCHAR(60)           DEFAULT '',
  location  VARCHAR(190)          DEFAULT '',
  bacenta   VARCHAR(190)          DEFAULT '',
  ministry  VARCHAR(120)          DEFAULT '',
  dob       DATE                  DEFAULT NULL,
  -- A photo is either a path under uploads/ or a data: URI.
  -- Paths keep this table small; see api/index.php savePhotos().
  photo     MEDIUMTEXT,
  joined    DATE                  DEFAULT NULL,
  created   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
                              ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_bacenta  (bacenta),
  KEY idx_ministry (ministry)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
--  bacentas — fellowship groups. Members reference these by
--  name, so renaming here does not break anything; the front
--  end keeps member rows in step when you rename in the app.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bacentas (
  id       VARCHAR(40)  NOT NULL,
  name     VARCHAR(190) NOT NULL,
  location VARCHAR(190)          DEFAULT '',
  created  DATETIME              DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_bacenta_name (name)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
--  attendance — one row per member per service.
--  Mirrors the front-end shape att[date][type][memberId] = status
--  ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS attendance (
  service_date DATE        NOT NULL,
  service_type VARCHAR(20) NOT NULL,   -- 'sunday' | 'midweek'
  member_id    VARCHAR(40) NOT NULL,
  status       VARCHAR(20) NOT NULL,   -- 'present' | 'absent'
  PRIMARY KEY (service_date, service_type, member_id),
  KEY idx_member (member_id),
  CONSTRAINT fk_att_member
    FOREIGN KEY (member_id) REFERENCES members (id)
    ON DELETE CASCADE
) ENGINE=InnoDB;

-- ------------------------------------------------------------
--  users — ready for real login. The app ships with demo auth
--  kept in the browser; wire api/auth.php to this table when
--  you want proper password sign-in.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id            INT          NOT NULL AUTO_INCREMENT,
  name          VARCHAR(190) NOT NULL,
  email         VARCHAR(190) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(40)  NOT NULL DEFAULT 'admin',
  created       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_user_email (email)
) ENGINE=InnoDB;

